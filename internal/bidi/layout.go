package bidi

// Driver entry points of the bidi layer: the conversion of character data (ToLogical,
// ToHost, with the deviations below), the string functions that JTOpen's JDBC driver
// applies to SQL text and column names (AS400BidiTransform.bidiTransform,
// SQL_statement_reordering, meta_data_reordering, convertSQLToHostCCSID,
// convertDataFromHostCCSID), and the CCSID lists those functions use.
//
// Deviation 4b (stale tail): JTOpen returns the complete data array of the destination, whose
// length is that of the source when marks were removed, so the tail after the valid characters
// holds stale characters. ToLogicalPadded and ToHostPadded replace that tail with U+0020. Use
// the Padded variants in the driver; ToLogical and ToHost stay faithful to JTOpen for the golden
// tests.
//
// Deviation 4a (shared flag sets): see as400transform.go.

// IsConversionBidiCCSID reports whether JTOpen converts the CCSID with a ConvTableBidiMap, that is
// whether the bidi layout is applied to character data of that CCSID. Generated by
// gen/BidiDriverGolden.java (ConvTable.getTable(ccsid) instanceof ConvTableBidiMap).
func IsConversionBidiCCSID(ccsid int) bool {
	switch ccsid {
	case 420, 424, 425, 862, 864, 916, 1046, 1089, 1255, 1256, 5351, 8612, 12708,
		62211, 62224, 62235, 62245, 62251:
		return true
	}
	return false
}

// SystemInfo describes the IBM i server for the string functions that depend on it.
// Present is false when the server is unknown (AS400 object null in JTOpen).
type SystemInfo struct {
	Present bool
	// CCSID is the server (job) CCSID.
	CCSID int
	// VRM is the server version in JTOpen's encoding (version<<16 | release<<8 | modification).
	VRM int
}

// isBidiSystemCCSID is AS400BidiTransform.isBidiCcsid.
func isBidiSystemCCSID(ccsid int) bool {
	switch ccsid {
	case 420, 424, 425, 856, 862, 864, 867, 916, 1046, 1089, 1255, 1256, 5012, 5351, 5352,
		8612, 8616, 9238, 12708, 12712, 13488, 16804, 17248, 61952, 62208, 62209, 62210, 62211:
		return true
	}
	return false
}

// StringTypeForSystem is AS400BidiTransform.getStringTypeX: the string type of a CCSID on the
// given server. Without server information it is StringTypeForCCSID.
func StringTypeForSystem(ccsid int, sys SystemInfo) int {
	if !sys.Present {
		return StringTypeForCCSID(ccsid)
	}
	if ccsid == 13488 || ccsid == 1200 {
		v5r1 := sys.VRM != 0 && sys.VRM>>8 == 0x0501
		if isBidiSystemCCSID(sys.CCSID) && !v5r1 {
			return StringTypeST10
		}
		return StringTypeST5
	}
	return StringTypeForCCSID(ccsid)
}

// ToLogicalPadded is ToLogical with deviation 4b: the stale tail is padded with spaces.
func ToLogicalPadded(text []uint16, ccsid int, props Properties) []uint16 {
	data, valid := toLogicalCount(text, ccsid, props)
	return padStaleTail(data, valid)
}

// ToHostPadded is ToHost with deviation 4b: the stale tail is padded with spaces.
func ToHostPadded(text []uint16, ccsid int, props Properties) []uint16 {
	data, valid := toHostCount(text, ccsid, props)
	return padStaleTail(data, valid)
}

// padStaleTail replaces the characters after the valid count with U+0020, in place.
func padStaleTail(data []uint16, valid int) []uint16 {
	if valid < 0 {
		valid = 0
	}
	for i := valid; i < len(data); i++ {
		data[i] = ' '
	}
	return data
}

// TransformString is AS400BidiTransform.bidiTransform(String, inFormat, outFormat): the layout of
// text converted from one string type to another, with markers removed. It returns text unchanged
// when the string types are equal or either is NONE.
func TransformString(text []uint16, inFormat, outFormat int) []uint16 {
	if inFormat == outFormat || inFormat == StringTypeNone || outFormat == StringTypeNone {
		return text
	}
	bdx := NewBidiTransform()
	bdx.Flags = initFlagSet(outFormat)
	bdx.RemoveMarkers = true
	in := NewBidiTextFromData(initFlagSet(inFormat), text)
	out := in.Transform(bdx)
	return out.Data[out.Offset : out.Offset+out.Count]
}

// SQLStatementReordering is AS400BidiTransform.SQL_statement_reordering: the layout of the
// text inside single-quoted literals (and across line breaks inside them) of an SQL statement.
// Identifiers and keywords are kept. The input slice is not modified.
func SQLStatementReordering(sql []uint16, inFormat, outFormat int) []uint16 {
	if inFormat == outFormat || inFormat == StringTypeNone || outFormat == StringTypeNone {
		return sql
	}
	value := append([]uint16(nil), sql...)
	into := false
	i, start, end := 0, 0, 0
	for i < len(value) {
		if into && (value[i] == '\n' || value[i] == '\r') {
			end = i
			value = replaceRange(value, start, end, TransformString(value[start:end], inFormat, outFormat))
			start = i + 1
		}
		if value[i] == '\'' {
			if into {
				if i+1 < len(value) && value[i+1] == '\'' {
					i += 2
					continue
				}
				end = i
				value = replaceRange(value, start, end, TransformString(value[start:end], inFormat, outFormat))
				start, end = 0, 0
				into = false
			} else {
				into = true
				start = i + 1
			}
		}
		i++
	}
	return value
}

// MetaDataReordering is AS400BidiTransform.meta_data_reordering: the layout of the text inside
// double-quoted identifiers of an SQL statement. The input slice is not modified.
func MetaDataReordering(sql []uint16, inFormat, outFormat int) []uint16 {
	if inFormat == outFormat || inFormat == StringTypeNone || outFormat == StringTypeNone {
		return sql
	}
	value := append([]uint16(nil), sql...)
	into := false
	i, start, end := 0, 0, 0
	for i < len(value) {
		if value[i] == '"' {
			if into {
				end = i
				value = replaceRange(value, start, end, TransformString(value[start:end], inFormat, outFormat))
				start, end = 0, 0
				into = false
			} else {
				into = true
				start = i + 1
			}
		}
		i++
	}
	return value
}

// replaceRange returns value with value[start:end] replaced by repl (Java: value.substring(0,start)
// + str + value.substring(end)).
func replaceRange(value []uint16, start, end int, repl []uint16) []uint16 {
	out := make([]uint16, 0, len(value)-(end-start)+len(repl))
	out = append(out, value[:start]...)
	out = append(out, repl...)
	out = append(out, value[end:]...)
	return out
}

// ConvertSQLToHost is AS400BidiTransform.convertSQLToHostCCSID: the layout applied to the SQL
// statement before it is converted to the package CCSID (JDSQLStatement). bidiType is the
// connection's bidi string type setting (-1 when not set), packageCCSID the package CCSID,
// implicitReordering the bidi implicit reordering setting.
func ConvertSQLToHost(sql []uint16, bidiType, packageCCSID int, implicitReordering bool, sys SystemInfo) []uint16 {
	hostType := 4
	if sys.Present {
		hostType = StringTypeForCCSID(sys.CCSID)
	}
	if bidiType == StringTypeNone || hostType == StringTypeNone {
		return sql
	}
	packageType := StringTypeForSystem(packageCCSID, sys)
	value := sql
	if implicitReordering {
		value = MetaDataReordering(value, bidiType, hostType)
	}
	return SQLStatementReordering(value, bidiType, packageType)
}

// ConvertDataFromHost is AS400BidiTransform.convertDataFromHostCCSID: the layout of a column name
// (metadata) from the layout of its CCSID to the connection's bidi string type. bidiType is the
// setting; 0 and -1 leave the text unchanged, as in JTOpen.
func ConvertDataFromHost(text []uint16, bidiType, hostCCSID int, sys SystemInfo) []uint16 {
	hostType := StringTypeForSystem(hostCCSID, sys)
	if hostType == 0 {
		if sys.Present {
			hostType = StringTypeForCCSID(sys.CCSID)
		} else {
			hostType = 4
		}
	}
	if bidiType != 0 && hostType != 0 {
		return TransformString(text, hostType, bidiType)
	}
	return text
}
